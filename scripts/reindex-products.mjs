import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { PRODUCTS } from './lib/product-config.mjs';
import { extractBrandTokens } from './lib/extract-brand.mjs';

// Weights bundled per family; add here if a design needs a heavier/lighter cut.
const FONT_WEIGHTS = [400, 500, 600, 700, 800];

mkdirSync('brands', { recursive: true });
for (const p of PRODUCTS) {
  if (!existsSync(p.repoPath)) { console.warn(`reindex-products: ${p.key} repo not found at ${p.repoPath}; keeping committed brand + profile`); continue; }
  const sources = p.brandGlobs
    .map((g) => path.join(p.repoPath, g))
    .filter(existsSync)
    .map((f) => readFileSync(f, 'utf8'));
  const tokens = extractBrandTokens(sources);
  if (Object.keys(tokens).length) {
    const body = Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`).join('\n');
    writeFileSync(`brands/${p.key}.css`, `[data-brand='${p.key}'] {\n${body}\n}\n`);
    console.log(`reindex-products: wrote brands/${p.key}.css (${Object.keys(tokens).length} tokens)`);
  }
}
// Derive the self-hosted webfont imports from each brand's --font-primary, so fonts stay in
// sync with the brand files and adding a product needs no manual edit here.
const families = [...new Set(
  readdirSync('brands').filter((f) => f.endsWith('.css'))
    .flatMap((f) => [...readFileSync(`brands/${f}`, 'utf8').matchAll(/--font-primary:\s*['"]([^'",]+)['"]/g)].map((m) => m[1].trim())),
)].sort();
const imports = [];
for (const family of families) {
  const slug = family.toLowerCase().replace(/\s+/g, '-');
  if (!existsSync(`node_modules/@fontsource/${slug}`)) {
    console.warn(`reindex-products: no @fontsource/${slug} for brand font "${family}" — run: npm i @fontsource/${slug}`);
    continue;
  }
  imports.push(`/* ${family} */`, ...FONT_WEIGHTS.map((w) => `@import '@fontsource/${slug}/${w}.css';`));
}
writeFileSync('src/styles/fonts.css',
  `/* generated by reindex-products from brands/*.css --font-primary. DO NOT EDIT.\n` +
  `   Self-hosted brand webfonts; family names match the brand tokens so the sandbox renders\n` +
  `   the real typeface instead of a system fallback. */\n${imports.join('\n')}\n`);
console.log(`reindex-products: wrote src/styles/fonts.css (${families.length} families)`);

console.log('reindex-products: product-profiles/*.md are maintained from codebase analysis; edit via profiling agents.');
